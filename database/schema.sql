    Id               UNIQUEIDENTIFIER NOT NULL DEFAULT NEWSEQUENTIALID(),
    RecipientUserId  UNIQUEIDENTIFIER NOT NULL,
    Type             VARCHAR(50)      NOT NULL,   -- event name from section 10.1, e.g. 'chatMessage'
    TitleAr          NVARCHAR(150)    NOT NULL,
    TitleEn          NVARCHAR(150)    NOT NULL,
    BodyAr           NVARCHAR(500)    NOT NULL,
    BodyEn           NVARCHAR(500)    NOT NULL,
    Route            VARCHAR(200)     NULL,       -- app route opened on tap
    DataJson         NVARCHAR(1000)   NULL,       -- ids for the route
    IsRead           BIT              NOT NULL DEFAULT 0,
    ReadAt           DATETIME2(3)     NULL,
    CreatedAt        DATETIME2(3)     NOT NULL DEFAULT SYSUTCDATETIME(),
    CONSTRAINT PK_Notifications PRIMARY KEY (Id),
    CONSTRAINT FK_Notifications_RecipientUserId FOREIGN KEY (RecipientUserId) REFERENCES dbo.Users (Id),
    CONSTRAINT CK_Notifications_Data CHECK (DataJson IS NULL OR ISJSON(DataJson) = 1)
);
CREATE INDEX IX_Notifications_Recipient        ON dbo.Notifications (RecipientUserId, CreatedAt DESC);
CREATE INDEX IX_Notifications_Recipient_Unread ON dbo.Notifications (RecipientUserId) WHERE IsRead = 0;

-- One log for the admin audit (AD15) and the clinic activity log (D27, filtered by DoctorId).
CREATE TABLE dbo.AuditLogs (
    Id           BIGINT           NOT NULL IDENTITY(1, 1),
    ActorUserId  UNIQUEIDENTIFIER NULL,       -- NULL = system job
    ActorRole    VARCHAR(10)      NOT NULL,
    DoctorId     UNIQUEIDENTIFIER NULL,       -- set for anything that happened in a clinic
    PatientId    UNIQUEIDENTIFIER NULL,       -- D27 shows and filters by patient
    Action       VARCHAR(50)      NOT NULL,   -- e.g. 'session.create', 'payment.approve'
    TargetType   VARCHAR(30)      NOT NULL,
    TargetId     VARCHAR(64)      NULL,
    DetailsJson  NVARCHAR(MAX)    NULL,
    At           DATETIME2(3)     NOT NULL DEFAULT SYSUTCDATETIME(),
    CONSTRAINT PK_AuditLogs PRIMARY KEY (Id),
    CONSTRAINT FK_AuditLogs_ActorUserId FOREIGN KEY (ActorUserId) REFERENCES dbo.Users (Id),
    CONSTRAINT FK_AuditLogs_DoctorId    FOREIGN KEY (DoctorId) REFERENCES dbo.Doctors (UserId),
    CONSTRAINT FK_AuditLogs_PatientId   FOREIGN KEY (PatientId) REFERENCES dbo.Patients (Id),
    CONSTRAINT CK_AuditLogs_ActorRole CHECK (ActorRole IN ('admin', 'doctor', 'assistant', 'patient', 'system')),
    CONSTRAINT CK_AuditLogs_Details   CHECK (DetailsJson IS NULL OR ISJSON(DetailsJson) = 1)
);
CREATE INDEX IX_AuditLogs_Doctor_At ON dbo.AuditLogs (DoctorId, At DESC) WHERE DoctorId IS NOT NULL;
CREATE INDEX IX_AuditLogs_Actor_At  ON dbo.AuditLogs (ActorUserId, At DESC);
CREATE INDEX IX_AuditLogs_Target    ON dbo.AuditLogs (TargetType, TargetId);
CREATE INDEX IX_AuditLogs_At        ON dbo.AuditLogs (At DESC);

