CREATE TABLE dbo.Users (
    Id                  UNIQUEIDENTIFIER NOT NULL DEFAULT NEWSEQUENTIALID(),
    Role                VARCHAR(10)      NOT NULL,
    AdminRole           VARCHAR(10)      NULL,
    Status              VARCHAR(10)      NOT NULL DEFAULT 'active',
    DisplayName         NVARCHAR(60)     NOT NULL,
    Phone               VARCHAR(16)      NULL,      -- E.164; patients and assistants sign in with it
    Email               NVARCHAR(254)    NULL,      -- doctors and admins sign in with it
    EmailVerifiedAt     DATETIME2(3)     NULL,      -- [S] A5
    PasswordHash        NVARCHAR(256)    NULL,      -- NULL until a new admin sets a password
    SecurityStamp       UNIQUEIDENTIFIER NOT NULL DEFAULT NEWID(),  -- change it to sign out other devices
    MustChangePassword  BIT              NOT NULL DEFAULT 0,        -- temporary passwords (BR-P4, BR-AS2)
    AccessFailedCount   INT              NOT NULL DEFAULT 0,
    LockoutEndAt        DATETIME2(3)     NULL,
    Locale              VARCHAR(2)       NOT NULL DEFAULT 'ar',     -- also the push notification language
    ThemeMode           VARCHAR(6)       NOT NULL DEFAULT 'system',
    NotifyChat          BIT              NOT NULL DEFAULT 1,
    NotifyReminders     BIT              NOT NULL DEFAULT 1,
    NotifyShowPreview   BIT              NOT NULL DEFAULT 0,        -- chat text in pushes, off by default
    NotifyBookings      BIT              NOT NULL DEFAULT 0,        -- doctor booking alerts, off by default (10.1)
    AcceptedTermsAt     DATETIME2(3)     NULL,
    CreatedAt           DATETIME2(3)     NOT NULL DEFAULT SYSUTCDATETIME(),
    UpdatedAt           DATETIME2(3)     NOT NULL DEFAULT SYSUTCDATETIME(),
    LastLoginAt         DATETIME2(3)     NULL,
    CONSTRAINT PK_Users PRIMARY KEY (Id),
    CONSTRAINT CK_Users_Role       CHECK (Role IN ('admin', 'doctor', 'assistant', 'patient')),
    CONSTRAINT CK_Users_AdminRole  CHECK ((Role = 'admin' AND AdminRole IN ('superAdmin', 'admin'))
                                       OR (Role <> 'admin' AND AdminRole IS NULL)),
    CONSTRAINT CK_Users_Status     CHECK (Status IN ('active', 'disabled')),
    CONSTRAINT CK_Users_Locale     CHECK (Locale IN ('ar', 'en')),
    CONSTRAINT CK_Users_ThemeMode  CHECK (ThemeMode IN ('system', 'light', 'dark')),
    CONSTRAINT CK_Users_Identifier CHECK (Phone IS NOT NULL OR Email IS NOT NULL),
    CONSTRAINT CK_Users_Phone      CHECK (Phone IS NULL OR Phone LIKE '+20[0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9]')
);
