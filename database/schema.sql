/* =============================================================================
   el3yada (العيادة) - SQL Server schema, version 1
   Source: spec.md section 8 (data model), 6 (business rules), 7 (screens), 9 (API).

   STATUS: original design, kept for reading. The database is now created by the EF Core
   migrations in backend/ (backend/README.md), which were generated from this script and
   checked against it object by object. Use `dotnet ef database update`, not this file.

   HOW TO RUN (only to rebuild the original design in an empty database)
     sqlcmd -S "(localdb)\MSSQLLocalDB" -Q "CREATE DATABASE el3yada_design"
     sqlcmd -S "(localdb)\MSSQLLocalDB" -d el3yada_design -b -f 65001 -i database/schema.sql
     sqlcmd -S "(localdb)\MSSQLLocalDB" -d el3yada_design -b -f 65001 -i database/seed.sql
   -f 65001 reads the files as UTF-8, so Arabic text is not corrupted.
   The script runs in one transaction: it creates everything or nothing.

   CONVENTIONS (everyone follows these when adding or changing tables)
     - Tables: PascalCase, plural (Users, Sessions). Columns: PascalCase.
     - Keys: Id UNIQUEIDENTIFIER DEFAULT NEWSEQUENTIALID(). Audit logs use BIGINT IDENTITY.
       One-to-one extensions of Users (Doctors, Assistants) use UserId as their key.
     - Constraint names: PK_Table, FK_Table_Column, UQ_Table_Columns, CK_Table_Rule, IX_Table_Columns.
     - Money: INT in piasters (1 EGP = 100). Column names end in "Piasters".
     - Time: DATETIME2 in UTC, names end in "At" (CreatedAt). Set by the server only.
       Clinic-local values use DATE / TIME (DayKey, LocalDate, StartLocal), in Africa/Cairo time.
       MonthKey is CHAR(7) 'YYYY-MM' in Cairo time.
     - Enums: VARCHAR with a CHECK constraint, values spelled exactly as in spec.md
       (e.g. 'examination', 'pendingApproval'). Flutter and the API use the same strings.
     - Phones: VARCHAR(16) in E.164 (+201XXXXXXXXX). Emails: lower case.
     - Text people type: NVARCHAR (Arabic). Codes and keys: VARCHAR.
     - Lists the API filters or joins on: a child table. Lists that are only stored and
       returned whole (aliases, reminder offsets, payment methods): NVARCHAR JSON with ISJSON.
     - Soft delete: Deleted BIT + DeletedAt + DeletedBy. Medical data is never hard-deleted.
     - Foreign keys never cascade. Deletes are soft, so cascades are not needed.
     - Hangfire creates its own tables (HangFire schema) on first start. Do not add them here.
     - Live board real-time data lives in Firestore (spec 9.6). SQL Server is the source of truth.
     - Medicine / lab / radiology catalogs live in a SQLite file on the device (spec 9.5).
       Only catalog versions, specialty profiles and admin custom items are stored here.

   CHANGING THE SCHEMA
     Do not edit this file. Change the entity in backend/src/El3yada.Data and add an EF Core
     migration (steps in backend/README.md), and tell the team. Update spec.md section 8 in
     the same pull request. The conventions above still apply to every new table and column.
   ============================================================================= */

